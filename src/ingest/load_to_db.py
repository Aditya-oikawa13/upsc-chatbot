"""Load extracted question JSON (data/extracted/**/*.json) into SQLite and
ChromaDB — the last step before the data is queryable by the agent layer.

- SQLite (questions.db) is the source of truth for all structured metadata.
- Chroma mirrors a filterable subset of metadata alongside the embedding, so
  retrieval can combine semantic search with hard filters (exam_type, year).

Embeddings are generated by Chroma's configured embedding function
(Vertex AI text-embedding-005, see embed/vertex_embedding_function.py) —
this script never calls the embedding API directly.

Usage:
    python -m src.ingest.load_to_db
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from ..db import init_db, vector_store
from .. import config

CHROMA_UPSERT_BATCH = 200


def normalize_option_label(label: str) -> str:
    """Collapse '(a)', 'a', 'A.', etc. to a bare lowercase letter."""
    cleaned = re.sub(r"[^a-dA-D]", "", label)
    return cleaned.lower() or label.strip().lower()


def load_records() -> list[dict]:
    records = []
    for path in sorted((config.DATA_DIR / "extracted").glob("**/*.json")):
        records.extend(json.loads(path.read_text()))
    return records


def embedding_text(record: dict) -> str:
    text = record["question_text"]
    if record["exam_type"] == "prelims":
        options = record.get("options") or []
        opt_str = " ".join(f"{o['label']}: {o['text']}" for o in options)
        text = f"{text} {opt_str}".strip()
    return text


def upsert_sqlite(conn, records: list[dict]) -> None:
    now_fields = (
        "question_id, exam_board, exam_type, is_objective, paper, year, "
        "question_number, question_text, options_json, correct_option, "
        "marks, word_limit, source_doc_url, extraction_method, extracted_at"
    )
    placeholders = ", ".join(f":{f.strip()}" for f in now_fields.split(","))
    sql = f"INSERT OR REPLACE INTO questions ({now_fields}) VALUES ({placeholders})"

    rows = []
    for r in records:
        options = r.get("options")
        if options:
            for o in options:
                o["label"] = normalize_option_label(o["label"])
        rows.append(
            {
                "question_id": r["question_id"],
                "exam_board": r["exam_board"],
                "exam_type": r["exam_type"],
                "is_objective": r["is_objective"],
                "paper": r["paper"],
                "year": r["year"],
                "question_number": r["question_number"],
                "question_text": r["question_text"],
                "options_json": json.dumps(options, ensure_ascii=False) if options else None,
                "correct_option": r.get("correct_option"),
                "marks": r.get("marks"),
                "word_limit": r.get("word_limit"),
                "source_doc_url": r["source_doc_url"],
                "extraction_method": r["extraction_method"],
                "extracted_at": r["extracted_at"],
            }
        )
    with conn:
        conn.executemany(sql, rows)


def upsert_chroma(collection, records: list[dict]) -> None:
    for i in range(0, len(records), CHROMA_UPSERT_BATCH):
        batch = records[i : i + CHROMA_UPSERT_BATCH]
        collection.upsert(
            ids=[r["question_id"] for r in batch],
            documents=[embedding_text(r) for r in batch],
            metadatas=[
                {
                    "exam_board": r["exam_board"],
                    "exam_type": r["exam_type"],
                    "paper": r["paper"],
                    "year": r["year"],
                }
                for r in batch
            ],
        )
        print(f"  embedded + upserted {min(i + CHROMA_UPSERT_BATCH, len(records))}/{len(records)}")


def run() -> None:
    init_db.init_db()
    records = load_records()
    print(f"Loaded {len(records)} records from data/extracted/")

    conn = init_db.get_connection()
    upsert_sqlite(conn, records)
    print(f"SQLite: upserted {len(records)} rows into questions.db")

    collection = vector_store.get_collection()
    upsert_chroma(collection, records)
    print(f"Chroma: collection now has {collection.count()} records")


if __name__ == "__main__":
    run()
